import os
import shutil
import logging
from typing import Dict, Any, List, Optional
import docx
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT

logger = logging.getLogger(__name__)

class DocxService:
    """
    Enterprise Word document generation and format-preserving editing service.
    """

    def create_document(
        self,
        output_path: str,
        title: str,
        subtitle: Optional[str] = None,
        sections: Optional[List[Dict[str, Any]]] = None,
        table_data: Optional[Dict[str, Any]] = None,
        brand_color_rgb: tuple = (30, 64, 175)  # Executive Navy
    ) -> str:
        """
        Creates a high-quality, professional corporate DOCX report from scratch.
        """
        doc = docx.Document()

        # Page setup - 1 inch margins
        for section in doc.sections:
            section.top_margin = Inches(1.0)
            section.bottom_margin = Inches(1.0)
            section.left_margin = Inches(1.0)
            section.right_margin = Inches(1.0)
            # Add Header & Footer
            header_para = section.header.paragraphs[0]
            header_para.text = f"{title} | Executive Document"
            header_para.alignment = WD_ALIGN_PARAGRAPH.RIGHT
            if header_para.runs:
                header_para.runs[0].font.size = Pt(8.5)
                header_para.runs[0].font.color.rgb = RGBColor(128, 128, 128)

            footer_para = section.footer.paragraphs[0]
            footer_para.text = "Confidential & Proprietary - Generated by AI Assistant"
            footer_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
            if footer_para.runs:
                footer_para.runs[0].font.size = Pt(8.5)
                footer_para.runs[0].font.color.rgb = RGBColor(128, 128, 128)

        # Title
        title_p = doc.add_paragraph()
        title_p.paragraph_format.space_before = Pt(12)
        title_p.paragraph_format.space_after = Pt(4)
        run_title = title_p.add_run(title)
        run_title.font.name = "Calibri"
        run_title.font.size = Pt(26)
        run_title.font.bold = True
        run_title.font.color.rgb = RGBColor(*brand_color_rgb)

        if subtitle:
            sub_p = doc.add_paragraph()
            sub_p.paragraph_format.space_after = Pt(18)
            run_sub = sub_p.add_run(subtitle)
            run_sub.font.name = "Calibri"
            run_sub.font.size = Pt(13)
            run_sub.font.italic = True
            run_sub.font.color.rgb = RGBColor(100, 116, 139)

        # Default sections if none provided
        if not sections:
            sections = [
                {
                    "heading": "1. Executive Summary",
                    "content": "This report provides an in-depth strategic analysis and executive briefing based on verified data and document synthesis."
                },
                {
                    "heading": "2. Key Objectives & Findings",
                    "content": "All strategic initiatives are aligned with core organizational milestones, performance metrics, and compliance standards."
                }
            ]

        for sec in sections:
            # Section Heading
            h_p = doc.add_paragraph()
            h_p.paragraph_format.space_before = Pt(16)
            h_p.paragraph_format.space_after = Pt(6)
            h_run = h_p.add_run(sec.get("heading", "Section"))
            h_run.font.name = "Calibri"
            h_run.font.size = Pt(16)
            h_run.font.bold = True
            h_run.font.color.rgb = RGBColor(*brand_color_rgb)

            # Content
            c_p = doc.add_paragraph()
            c_p.paragraph_format.line_spacing = 1.15
            c_p.paragraph_format.space_after = Pt(8)
            c_run = c_p.add_run(sec.get("content", ""))
            c_run.font.name = "Calibri"
            c_run.font.size = Pt(11)

            # Bullet points if any
            bullets = sec.get("bullets", [])
            for b in bullets:
                b_p = doc.add_paragraph(style='List Bullet')
                b_run = b_p.add_run(b)
                b_run.font.name = "Calibri"
                b_run.font.size = Pt(11)

        # Add Table if provided or generated
        if table_data:
            headers = table_data.get("headers", ["Item", "Category", "Status", "Notes"])
            rows = table_data.get("rows", [
                ["Deliverable Alpha", "Technical", "Completed", "Signed off by engineering"],
                ["Deliverable Beta", "Operational", "In Progress", "Deployment underway"],
                ["Deliverable Gamma", "Review", "Pending", "Scheduled for next sprint"]
            ])

            t_p = doc.add_paragraph()
            t_p.paragraph_format.space_before = Pt(14)
            t_run = t_p.add_run(table_data.get("title", "Project Overview & Status"))
            t_run.font.name = "Calibri"
            t_run.font.size = Pt(13)
            t_run.font.bold = True
            t_run.font.color.rgb = RGBColor(*brand_color_rgb)

            table = doc.add_table(rows=1, cols=len(headers))
            table.alignment = WD_TABLE_ALIGNMENT.CENTER
            table.style = 'Light Shading Accent 1' if 'Light Shading Accent 1' in [s.name for s in doc.styles] else 'Table Grid'

            hdr_cells = table.rows[0].cells
            for idx, text in enumerate(headers):
                hdr_cells[idx].text = str(text)
                for run in hdr_cells[idx].paragraphs[0].runs:
                    run.font.bold = True
                    run.font.color.rgb = RGBColor(255, 255, 255)

            for row_vals in rows:
                row_cells = table.add_row().cells
                for idx, text in enumerate(row_vals):
                    row_cells[idx].text = str(text)

        os.makedirs(os.path.dirname(output_path), exist_ok=True)
        doc.save(output_path)
        logger.info(f"Generated DOCX saved to {output_path}")
        return output_path

    def edit_existing_docx(
        self,
        source_path: str,
        output_path: str,
        replacements: Optional[Dict[str, str]] = None,
        section_additions: Optional[List[Dict[str, Any]]] = None,
        instructions: str = ""
    ) -> Dict[str, Any]:
        """
        Critical Requirement: Targeted editing while strictly preserving original formatting,
        styles, fonts, colors, headers, footers, and table aesthetics.
        Never overwrites source_path.
        """
        if not os.path.exists(source_path):
            raise FileNotFoundError(f"Source document not found: {source_path}")

        # Load document without re-creating it
        doc = docx.Document(source_path)

        diff_summary = {
            "source_file": os.path.basename(source_path),
            "output_file": os.path.basename(output_path),
            "modified_paragraphs": 0,
            "modified_runs": 0,
            "added_sections": 0,
            "modified_table_cells": 0,
            "changes_log": []
        }

        # 1. Apply run-level text replacements (preserves exact run styling & typography)
        if replacements:
            for p_idx, p in enumerate(doc.paragraphs):
                orig_text = p.text
                if not orig_text.strip():
                    continue

                for target_str, new_val in replacements.items():
                    if target_str.lower() in orig_text.lower():
                        # Find and update preserving run formats where possible
                        if p.runs:
                            # If single run or simple paragraph, replace in the first run and clear subsequent
                            matched = False
                            for r in p.runs:
                                if target_str.lower() in r.text.lower():
                                    # Case-insensitive replacement preserving casing style
                                    start_i = r.text.lower().find(target_str.lower())
                                    end_i = start_i + len(target_str)
                                    r.text = r.text[:start_i] + new_val + r.text[end_i:]
                                    matched = True
                                    diff_summary["modified_runs"] += 1
                                    diff_summary["changes_log"].append({
                                        "type": "targeted_replacement",
                                        "target": target_str,
                                        "replacement": new_val,
                                        "location": f"Paragraph {p_idx}"
                                    })
                                    break
                            if not matched:
                                # Replace at paragraph level while preserving first run's font/bold/color
                                sample_run = p.runs[0]
                                font_name = sample_run.font.name
                                font_size = sample_run.font.size
                                font_bold = sample_run.font.bold
                                font_color = sample_run.font.color.rgb if sample_run.font.color else None
                                
                                p.text = orig_text.replace(target_str, new_val)
                                if p.runs:
                                    p.runs[0].font.name = font_name
                                    p.runs[0].font.size = font_size
                                    p.runs[0].font.bold = font_bold
                                    if font_color:
                                        p.runs[0].font.color.rgb = font_color
                                diff_summary["modified_paragraphs"] += 1

        # 2. Modify table cells if targets found in tables
        if replacements:
            for t_idx, table in enumerate(doc.tables):
                for r_idx, row in enumerate(table.rows):
                    for c_idx, cell in enumerate(row.cells):
                        cell_text = cell.text
                        for target_str, new_val in replacements.items():
                            if target_str.lower() in cell_text.lower():
                                # Target cell found, modify while preserving paragraph style
                                if cell.paragraphs and cell.paragraphs[0].runs:
                                    cell.paragraphs[0].text = cell_text.replace(target_str, new_val)
                                    diff_summary["modified_table_cells"] += 1
                                    diff_summary["changes_log"].append({
                                        "type": "table_cell_update",
                                        "target": target_str,
                                        "replacement": new_val,
                                        "location": f"Table {t_idx}, Row {r_idx}, Col {c_idx}"
                                    })

        # 3. Add new sections if requested
        if section_additions:
            # Detect primary font and style from existing document
            detected_font = "Calibri"
            detected_color = RGBColor(30, 64, 175)
            for p in doc.paragraphs:
                for r in p.runs:
                    if r.font.name:
                        detected_font = r.font.name
                    if r.font.color and r.font.color.rgb:
                        detected_color = r.font.color.rgb
                    if detected_font and detected_color:
                        break

            for sec in section_additions:
                # Add Heading
                h_p = doc.add_paragraph()
                h_p.paragraph_format.space_before = Pt(14)
                h_p.paragraph_format.space_after = Pt(4)
                h_run = h_p.add_run(sec.get("heading", "New Section"))
                h_run.font.name = detected_font
                h_run.font.size = Pt(14)
                h_run.font.bold = True
                h_run.font.color.rgb = detected_color

                # Add Body Content
                c_p = doc.add_paragraph()
                c_p.paragraph_format.space_after = Pt(8)
                c_run = c_p.add_run(sec.get("content", ""))
                c_run.font.name = detected_font
                c_run.font.size = Pt(11)

                diff_summary["added_sections"] += 1
                diff_summary["changes_log"].append({
                    "type": "section_added",
                    "heading": sec.get("heading"),
                    "details": "Appended with detected document typography"
                })

        # Save to output_path
        os.makedirs(os.path.dirname(output_path), exist_ok=True)
        doc.save(output_path)
        logger.info(f"Targeted DOCX edits preserved formatting and saved to {output_path}")
        return diff_summary

docx_service = DocxService()
