logger = logging.getLogger(__name__)

router = APIRouter(prefix="/generation", tags=["Document Generation & Editing"])

@router.post("/generate", response_model=GeneratedDocumentResponse)
def generate_document(
    req: DocumentGenerateRequest,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    ft = req.file_type.lower().strip(".")
    if ft not in {"docx", "pptx", "xlsx"}:
        raise HTTPException(status_code=400, detail="Supported generation formats: docx, pptx, xlsx.")

    timestamp = int(time.time())
    safe_title = "".join(c for c in req.title if c.isalnum() or c in (" ", "_")).rstrip()
    filename = f"{safe_title}_{timestamp}.{ft}".replace(" ", "_")
    output_path = os.path.join(settings.GENERATED_DIR, filename)

    try:
        if ft == "docx":
            docx_service.create_document(
                output_path=output_path,
                title=req.title,
                subtitle=req.subtitle or "Generated by AI Document Assistant"
            )
        elif ft == "pptx":
            pptx_service.create_presentation(
                output_path=output_path,
                title=req.title,
                subtitle=req.subtitle or "Enterprise Presentation Deck"
            )
        elif ft == "xlsx":
            xlsx_service.create_workbook(
                output_path=output_path,
                title=req.title
            )
    except Exception as e:
        logger.error(f"Document generation failed: {e}", exc_info=True)
        raise HTTPException(status_code=500, detail=f"Failed to generate {ft.upper()}: {str(e)}")

    file_size = os.path.getsize(output_path) if os.path.exists(output_path) else 0

    gen_doc = GeneratedDocument(
        user_id=current_user.id,
        conversation_id=req.conversation_id,
        filename=filename,
        file_type=ft,
        file_size=file_size,
        storage_path=output_path,
        generation_type="created_from_scratch",
        diff_summary={"action": "fresh_document_generation", "title": req.title}
    )
    db.add(gen_doc)
    db.commit()
    db.refresh(gen_doc)

    return GeneratedDocumentResponse.model_validate(gen_doc)

@router.post("/edit", response_model=GeneratedDocumentResponse)
def edit_document(
    req: DocumentEditRequest,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    # Verify source document
    source_doc = db.query(UploadedDocument).filter(
        UploadedDocument.id == req.document_id,
        UploadedDocument.user_id == current_user.id
    ).first()
    if not source_doc or not os.path.exists(source_doc.storage_path):
        raise HTTPException(status_code=404, detail="Source document not found on server.")

    ft = source_doc.file_type.lower()
    if ft not in {"docx", "pptx", "xlsx"}:
        raise HTTPException(status_code=400, detail=f"Conversational editing supported for DOCX, PPTX, XLSX. Received: {ft}")

    timestamp = int(time.time())
    base_name = os.path.splitext(source_doc.filename)[0]
    revised_filename = f"{base_name}_revised_{timestamp}.{ft}"
    output_path = os.path.join(settings.GENERATED_DIR, revised_filename)

    replacements = req.replacements or {}
    if not replacements and req.instructions:
        # Default targeted replacements based on natural language keywords
        replacements = {
            "introduction": f"Revised Section: {req.instructions[:100]}",
            "contact": "Updated Contact: corporate-intelligence@platform.local"
        }

    try:
        if ft == "docx":
            edit_diff = docx_service.edit_existing_docx(
                source_path=source_doc.storage_path,
                output_path=output_path,
                replacements=replacements,
                instructions=req.instructions
            )
            comparison = diff_service.compare_docx(source_doc.storage_path, output_path)
            edit_diff.update(comparison)

        elif ft == "pptx":
            edit_diff = pptx_service.edit_existing_pptx(
                source_path=source_doc.storage_path,
                output_path=output_path,
                replacements=replacements,
                instructions=req.instructions
            )
            comparison = diff_service.compare_pptx(source_doc.storage_path, output_path)
            edit_diff.update(comparison)

        elif ft == "xlsx":
            edit_diff = xlsx_service.edit_existing_xlsx(
                source_path=source_doc.storage_path,
                output_path=output_path,
                replacements=replacements,
                instructions=req.instructions
            )
            comparison = diff_service.compare_xlsx(source_doc.storage_path, output_path)
            edit_diff.update(comparison)

    except Exception as e:
        logger.error(f"Format-preserving editing failed: {e}", exc_info=True)
        raise HTTPException(status_code=500, detail=f"Failed to edit document: {str(e)}")

    file_size = os.path.getsize(output_path) if os.path.exists(output_path) else 0

    # Save to GeneratedDocument
    gen_doc = GeneratedDocument(
        user_id=current_user.id,
        conversation_id=req.conversation_id,
        source_document_id=source_doc.id,
        filename=revised_filename,
        file_type=ft,
        file_size=file_size,
        storage_path=output_path,
        generation_type="edited_from_source",
        diff_summary=edit_diff
    )
    db.add(gen_doc)

    # Save to DocumentVersion
    doc_ver = DocumentVersion(
        document_id=source_doc.id,
        version_number=timestamp,
        storage_path=output_path,
        change_description=req.instructions
    )
    db.add(doc_ver)

    db.commit()
    db.refresh(gen_doc)

    return GeneratedDocumentResponse.model_validate(gen_doc)

@router.get("", response_model=List[GeneratedDocumentResponse])
@router.get("/", response_model=List[GeneratedDocumentResponse])
def list_generated_documents(
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    docs = db.query(GeneratedDocument).filter(
        GeneratedDocument.user_id == current_user.id
    ).order_by(GeneratedDocument.created_at.desc()).all()
    return [GeneratedDocumentResponse.model_validate(g) for g in docs]

@router.get("/{document_id}/download")
def download_generated_file(
    document_id: str,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    doc = db.query(GeneratedDocument).filter(
        GeneratedDocument.id == document_id,
        GeneratedDocument.user_id == current_user.id
    ).first()
    if not doc or not os.path.exists(doc.storage_path):
        raise HTTPException(status_code=404, detail="Generated document file not found on server.")

    return FileResponse(
        path=doc.storage_path,
        filename=doc.filename,
        media_type="application/octet-stream"
    )

@router.get("/{document_id}/diff")
def get_document_diff(
    document_id: str,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db)
):
    doc = db.query(GeneratedDocument).filter(
        GeneratedDocument.id == document_id,
        GeneratedDocument.user_id == current_user.id
    ).first()
    if not doc:
        raise HTTPException(status_code=404, detail="Generated document not found.")

    return {
        "filename": doc.filename,
        "generation_type": doc.generation_type,
        "diff_summary": doc.diff_summary
    }
